def test_golden_rows_cover_exact_approved_25():
    text = (ROOT / "docs/iterations/I03/I05-semantic-boundaries.md").read_text()
    table = text.split("| 当前内部细码", 1)[1].split("新表需要", 1)[0]
    reasons = {
        line.split("|")[1].strip() for line in table.splitlines()[2:] if line.startswith("|")
    }
    assert len(APPROVED_25) == 25
    assert {row[0] for row in APPROVED_25} == reasons


