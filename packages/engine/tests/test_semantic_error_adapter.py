def test_message_key_and_retryable_are_derived_from_consistent_canonical_documents(documents):
    catalog, schema = documents
    # A constructor provenance check only: both supplied documents change together.
    # No production canonical source is edited or alternate directory introduced.
    catalog["codes"]["INTERNAL_ERROR"].update(messageKey="catalog.dynamicInternal", retryable=True)
    branch = next(
        b
        for b in schema["$defs"]["error"]["oneOf"]
        if b["properties"]["code"]["const"] == "INTERNAL_ERROR"
    )
    branch["properties"]["messageKey"]["const"] = "catalog.dynamicInternal"
    branch["properties"]["retryable"]["const"] = True
