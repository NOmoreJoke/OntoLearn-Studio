def test_exact_output_byte_budget_and_one_byte_overflow_configuration(documents):
    catalog, schema = documents
    branch = next(
        b
        for b in schema["$defs"]["error"]["oneOf"]
        if b["properties"]["code"]["const"] == "INTERNAL_ERROR"
    )
    empty = {**INTERNAL, "messageKey": ""}
    length = 2048 - len(json.dumps(empty, separators=(",", ":")).encode())
    key = "x" * length
    catalog["codes"]["INTERNAL_ERROR"]["messageKey"] = key
    branch["properties"]["messageKey"]["const"] = key
    adapter = SemanticErrorAdapter(error_catalog=catalog, error_schema=schema)
    dto = adapter.adapt(producer=None, reason=None, context=None)
    assert len(json.dumps(dto, separators=(",", ":")).encode()) == 2048
    assert CONTRACT.check(schema["$defs"]["error"], dto)
    catalog["codes"]["INTERNAL_ERROR"]["messageKey"] += "x"
    branch["properties"]["messageKey"]["const"] += "x"
    with pytest.raises(ValueError, match="^SEMANTIC_ERROR_CATALOG_INVALID$"):
        SemanticErrorAdapter(error_catalog=catalog, error_schema=schema)
