async function loadFact(page: Page, fact: Fact) {
  const search = panel(page).getByRole('textbox', { name: '查找事实', exact: true })
  await search.fill(fact.id)
  const table = panel(page)
    .getByRole('region', { name: '实例事实', exact: true })
    .getByRole('table')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await table.getByRole('button', { name: '载入事实', exact: true }).click()
  await expect(
    panel(page).locator('p').filter({ hasText: '原记录 ID：' }).locator('code'),
  ).toHaveText(fact.id)
  await expect(
    panel(page).getByRole('textbox', { name: '主体个体 IRI', exact: true }),
  ).toBeDisabled()
  await expect(panel(page).getByRole('textbox', { name: '属性 IRI', exact: true })).toBeDisabled()
  await expect(
    panel(page).getByRole('textbox', { name: '规范 RDF 对象', exact: true }),
  ).toHaveValue(fact.object!)
}
