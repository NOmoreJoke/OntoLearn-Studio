/** Actual UI definitions, not execution evidence. No production mapper imports,
 * bridge writes, seeded database, authority replacement, or restart instrumentation.
 * Empty projects are created through UI; all domain mutations use visible forms,
 * complete Diff and explicit confirmation. Named bridge calls below only observe.
 */
