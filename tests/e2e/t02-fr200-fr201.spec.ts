async function read(page: Page): Promise<Read> {
  return data(
    await page.evaluate(() => window.ontolearn!.readProject({ editor: 'ontology-transaction' })),
  )
}
async function diff(page: Page): Promise<Diff[]> {
  const region = panel(page).getByRole('region', { name: '完整事务差异', exact: true })
  await expect(region).toBeVisible()
  await expect(
    region.getByRole('button', { name: '我已核对完整差异，确认提交', exact: true }),
  ).toBeEnabled()
  const text = await region.locator('pre').textContent()
  const parsed: unknown = JSON.parse(text ?? 'null')
  if (!Array.isArray(parsed)) throw new Error('Actual complete Diff is not an array')
  return parsed as Diff[]
}
function sortDefinitions(rows: Definition[]): Definition[] {
  return [...rows].sort((a, b) => {
    const left = `${a.layer}\0${a.id}`,
      right = `${b.layer}\0${b.id}`
    return left < right ? -1 : left > right ? 1 : 0
  })
}
function sortFacts(rows: Fact[]): Fact[] {
  return [...rows].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
}

async function commit(
  page: Page,
  action: string,
  before: Read,
  expected: Diff[],
  evidence: Evidence[],
): Promise<Read> {
  expect(await diff(page)).toEqual(expected)
  await expect(
    panel(page).getByRole('region', { name: '完整事务差异', exact: true }),
  ).toContainText(`全部 ${expected.length} 项；`)
  const uncommitted = await read(page)
  expect(uncommitted.domain).toEqual(before.domain)
  expect(uncommitted.inputSnapshotId).toBe(before.inputSnapshotId)
  await panel(page)
    .getByRole('region', { name: '完整事务差异', exact: true })
    .getByRole('button', { name: '我已核对完整差异，确认提交', exact: true })
    .click()
  const revision = before.domain.projectRevision + 1
  const receipt = panel(page).getByRole('region', { name: '已提交回执', exact: true })
  const pending = panel(page).getByRole('region', { name: '原操作状态', exact: true })
  let reconcile = false
  await expect
    .poll(async () => {
      const observed = await receipt.or(pending).evaluateAll((nodes) => ({
        receipt: nodes.find((node) => node.getAttribute('aria-label') === '已提交回执')
          ?.textContent,
        pending: nodes.find((node) => node.getAttribute('aria-label') === '原操作状态')
          ?.textContent,
      }))
      if (observed.receipt?.includes(`提交版本 ${revision}。`)) return true
      if (observed.pending?.includes('succeeded')) {
        reconcile = true
        return true
      }
      return false
    })
    .toBe(true)
  if (reconcile) {
    const button = pending.getByRole('button', { name: '核对原操作与提交回执', exact: true })
    await expect(button).toBeEnabled()
    await button.click()
  }
  await expect(receipt).toContainText(`提交版本 ${revision}。`)
  await expect(receipt).toContainText(`当前已读版本 ${revision}。`)
  await expect(pending).toHaveCount(0)
  const operationId = (await receipt.locator('p').first().textContent())?.match(
    new RegExp(`操作 (${UUID})，`),
  )?.[1]
  if (!operationId) throw new Error('Visible receipt lacks its original operation ID')
  const marker = data(await page.evaluate((id) => window.ontolearn!.getOperation(id), operationId))
  if (!marker || typeof marker.jobId !== 'string')
    throw new Error('Original operation marker missing')
  const job = data(await page.evaluate((id) => window.ontolearn!.getJob(id), marker.jobId))
  expect(job.jobId).toMatch(new RegExp(`^${UUID}$`))
  const after = await read(page)
  expect(after.projectId).toBe(before.projectId)
  expect(after.domain.projectRevision).toBe(revision)
  expect(after.inputSnapshotId).toMatch(hash)
  expect(after.inputSnapshotId).not.toBe(before.inputSnapshotId)
  expect(marker).toEqual({
    projectId: before.projectId,
    operationId,
    jobId: job.jobId,
    projectRevision: revision,
    beforeSnapshotId: before.inputSnapshotId,
    afterSnapshotId: after.inputSnapshotId,
    planHash: expect.stringMatching(hash),
  })
  expect(job).toMatchObject({
    projectId: before.projectId,
    operationId,
    capability: 'changeset.commit',
    state: 'succeeded',
    error: null,
    inputSnapshotId: before.inputSnapshotId,
  })
  expect(job.input).toEqual({
    inputSnapshotId: before.inputSnapshotId,
    scope: 'asserted',
    definitionId: 'changeset',
    parametersHash: job.parametersHash,
    derivedResultIds: [],
    preparedPlanRef: expect.stringMatching(hash),
  })
  expect(job.confirmationRef).toEqual(expect.any(String))
  expect(job.confirmationRef).not.toBe('')
  expect(job.commitProgress).toEqual({
    mode: 'atomic',
    operationId,
    marker: {
      projectRevision: revision,
      beforeSnapshotId: before.inputSnapshotId,
      afterSnapshotId: after.inputSnapshotId,
      planHash: marker.planHash,
    },
  })
  expect(
    evidence.map((item) => (item.marker as { operationId: string }).operationId),
  ).not.toContain(operationId)
  expect(after.domain.state.mappingState).toEqual(before.domain.state.mappingState)
  // UI manual deletion does not manufacture managed tombstones. Preserve any
  // real ones present; these blank UI-created projects start with none, so this
  // assertion must not be reported as nonempty managed-tombstone coverage.
  expect(after.domain.state.facts.filter((fact) => fact.object === null)).toEqual(
    before.domain.state.facts.filter((fact) => fact.object === null),
  )
  evidence.push({ action, before, after, diff: expected, marker, job })
  const refresh = panel(page).getByRole('button', { name: '读取当前项目', exact: true })
  await expect(refresh).toBeEnabled()
  await refresh.click()
  await expect(refresh).toBeEnabled()
  expect((await read(page)).domain).toEqual(after.domain)
  return after
}

async function fields(page: Page, entity: Entity, initial: boolean) {
  const target = form(page)
  await target.getByLabel('英文标识', { exact: true }).fill(entity.metadata.identifier)
  for (const [title, pairs] of [
    ['名称', entity.metadata.labels],
    ['定义', entity.metadata.definitions],
  ] as const) {
    const group = target.getByRole('group', { name: `${title}（保留所有语言）`, exact: true })
    for (const [index, [text, language]] of pairs.entries()) {
      if (initial) await group.getByRole('button', { name: `添加${title}`, exact: true }).click()
      await group.getByRole('textbox', { name: `${title} ${index + 1}`, exact: true }).fill(text)
      await group.getByLabel(`语言标签 ${index + 1}`, { exact: true }).fill(language)
    }
  }
  for (const [title, values] of [
    ['同义词', entity.metadata.synonyms],
    ['示例', entity.metadata.examples],
  ] as const) {
    const group = target.getByRole('group', { name: `${title}（保留原文与顺序）`, exact: true })
    for (const [index, text] of values.entries()) {
      if (initial) await group.getByRole('button', { name: `添加${title}`, exact: true }).click()
      await group.getByRole('textbox', { name: `${title} ${index + 1}`, exact: true }).fill(text)
    }
  }
  for (const [key, label] of [
    ['parents', '上级类 IRI'],
    ['domain', '适用主体类 IRI（定义域）'],
    ['range', '客体类 / 数据类型 IRI（值域）'],
    ['types', '所属类 IRI'],
  ] as const) {
    // Populated textareas contribute default text to getByLabel's label text.
    // Match the exact accessible textbox name, independent of its current value.
    if (entity[key] !== undefined)
      await target
        .getByRole('textbox', { name: `${label}（每行一项）`, exact: true })
        .fill(entity[key])
  }
}
async function select(page: Page, entity: Entity) {
  const browser = panel(page).getByRole('region', { name: '对象浏览', exact: true })
  await browser.getByRole('button', { name: '表格', exact: true }).click()
  await browser.getByRole('textbox', { name: '查找概念', exact: true }).fill(entity.iri)
  await browser
    .getByRole('button', { name: `查看 ${entity.metadata.identifier}`, exact: true })
    .click()
  await expect(
    panel(page).getByRole('article', { name: '选中对象详情', exact: true }).locator('code'),
  ).toHaveText(entity.iri)
}
async function create(
  page: Page,
  entity: Entity,
  before: Read,
  evidence: Evidence[],
): Promise<Read> {
  await panel(page).getByRole('button', { name: '新建概念', exact: true }).click()
  await form(page).getByRole('combobox', { name: '类型', exact: true }).selectOption(entity.kind)
  if (entity.classType)
    await form(page)
      .getByRole('combobox', { name: '类声明', exact: true })
      .selectOption(entity.classType)
  await form(page).getByLabel('稳定 IRI', { exact: true }).fill(entity.iri)
  await fields(page, entity, true)
  await form(page).getByRole('button', { name: '预览定义修改', exact: true }).click()
  const rows = await diff(page)
  expect(rows).toHaveLength(1)
  expect(rows[0]?.resource).toEqual([
    'definition',
    'ontology',
    expect.stringMatching(new RegExp(`^t02-${UUID}$`)),
  ])
  const home = rows[0]!.resource[2]!
  const expectedRecord = record(home, entity)
  const after = await commit(
    page,
    `create ${entity.iri}`,
    before,
    [{ resource: ['definition', 'ontology', home], before: null, after: expectedRecord }],
    evidence,
  )
  expect(after.domain.state).toEqual({
    ...before.domain.state,
    definitions: sortDefinitions([...before.domain.state.definitions, expectedRecord]),
  })
  // Structure/class/type/domain/range metadata never creates instance relation facts.
  expect(after.domain.state.facts).toEqual(before.domain.state.facts)
  return after
}
function homeOf(source: Read, entity: Entity): Definition {
  const records = source.domain.state.definitions.filter((item) => {
    if (item.layer !== 'ontology') return false
    const value: unknown = JSON.parse(item.payload)
    if (!value || typeof value !== 'object' || !('entityMetadata' in value)) return false
    const metadata = value.entityMetadata as { entities: Record<string, unknown> }
    return Object.hasOwn(metadata.entities, entity.iri)
  })
  expect(records).toHaveLength(1)
  return records[0]!
}
async function edit(
  page: Page,
  original: Entity,
  changed: Entity,
  before: Read,
  evidence: Evidence[],
): Promise<Read> {
  await select(page, original)
  await panel(page).getByRole('button', { name: '将对象载入编辑表单', exact: true }).click()
  await expect(form(page).getByLabel('稳定 IRI', { exact: true })).toBeDisabled()
  await fields(page, changed, false)
  await form(page).getByRole('button', { name: '预览定义修改', exact: true }).click()
  const old = homeOf(before, original),
    next = record(old.id, changed)
  const after = await commit(
    page,
    `edit ${original.iri}`,
    before,
    [{ resource: ['definition', 'ontology', old.id], before: old, after: next }],
    evidence,
  )
  expect(after.domain.state).toEqual({
    ...before.domain.state,
    definitions: before.domain.state.definitions.map((row) =>
      row.layer === old.layer && row.id === old.id ? next : row,
    ),
  })
  return after
}
async function removeEntity(
  page: Page,
  entity: Entity,
  before: Read,
  evidence: Evidence[],
): Promise<Read> {
  await select(page, entity)
  const article = panel(page).getByRole('article', { name: '选中对象详情', exact: true })
  await article.getByRole('button', { name: '查看删除影响', exact: true }).click()
  await expect(article.getByText('当前未发现已登记的引用。', { exact: true })).toBeVisible()
  await article.getByRole('button', { name: '预览删除（尚不提交）', exact: true }).click()
  const old = homeOf(before, entity),
    next = record(old.id)
  const after = await commit(
    page,
    `delete ${entity.iri}`,
    before,
    [{ resource: ['definition', 'ontology', old.id], before: old, after: next }],
    evidence,
  )
  expect(after.domain.state).toEqual({
    ...before.domain.state,
    definitions: before.domain.state.definitions.map((row) =>
      row.layer === old.layer && row.id === old.id ? next : row,
    ),
  })
  return after
}

